    required this.title,
    required this.subtitle,
    required this.icon,
    this.onTap,
    this.busy = false,
  });

  @override
  Widget build(BuildContext context) {
    return ListTile(
      contentPadding: const EdgeInsets.symmetric(horizontal: 14, vertical: 2),
      leading: Icon(icon, size: 20, color: LoreColors.secondary),
      title: Text(
        title,
        style: LoreTypography.bodyMd.copyWith(
          color: LoreColors.onSurface,
          fontWeight: FontWeight.w500,
        ),
      ),
      subtitle: Text(
        subtitle,
        style: LoreTypography.bodySm.copyWith(color: LoreColors.secondary),
      ),
      trailing: busy
          ? const SizedBox(
              width: 16,
              height: 16,
              child: CircularProgressIndicator(strokeWidth: 2),
            )
          : const Icon(
              Icons.chevron_right,
              size: 18,
              color: LoreColors.secondary,
            ),
      onTap: onTap,
    );
  }
}

