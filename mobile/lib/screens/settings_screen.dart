class SettingsScreen extends StatefulWidget {
  const SettingsScreen({super.key});

  @override
  State<SettingsScreen> createState() => _SettingsScreenState();
}

class _SettingsScreenState extends State<SettingsScreen> {
  String? _runningAction;

  void _showSnack(String message) {
    if (!mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(content: Text(message), behavior: SnackBarBehavior.floating),
    );
  }

  Future<bool> _confirm({
    required String title,
    required String message,
    String confirmLabel = 'Confirm',
  }) async {
    final result = await showDialog<bool>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: Text(title),
        content: Text(message),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(dialogContext).pop(false),
            child: const Text('Cancel'),
          ),
          FilledButton(
            onPressed: () => Navigator.of(dialogContext).pop(true),
            child: Text(confirmLabel),
          ),
        ],
      ),
    );
    return result == true;
  }

  Future<void> _openAiModeSheet() async {
    final appState = context.read<AppState>();
    await showModalBottomSheet<void>(
      context: context,
      showDragHandle: true,
      builder: (sheetContext) {
        return SafeArea(
          child: SingleChildScrollView(
            padding: const EdgeInsets.fromLTRB(16, 0, 16, 20),
            child: Column(
              mainAxisSize: MainAxisSize.min,
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  'AI processing',
                  style: LoreTypography.headlineSm.copyWith(
                    color: LoreColors.onSurface,
                  ),
                ),
                const SizedBox(height: 4),
                Text(
                  'Choose how LORE answers your questions. The app never '
                  'switches modes silently.',
                  style: LoreTypography.bodySm.copyWith(
                    color: LoreColors.secondary,
                    height: 1.5,
                  ),
                ),
                const SizedBox(height: 16),
                _ModeOption(
                  title: 'Private',
                  badge: 'No external requests',
                  description:
                      'Answers are extracted from your indexed documents or '
                      'generated by a model on the LORE backend host. Nothing '
                      'is sent to an external AI provider.',
                  selected: !appState.isAssistedMode,
                  enabled: true,
                  onTap: () {
                    Navigator.of(sheetContext).pop();
                    _applyMode('private');
                  },
                ),
                const SizedBox(height: 10),
                _ModeOption(
                  title: 'Assisted',
                  badge: 'Approval required',
                  description: appState.assistedAvailable
                      ? 'LORE prepares the excerpts for each question, then '
                            'waits for your explicit approval before sending '
                            'anything to the configured external provider.'
                      : 'Unavailable. ${appState.externalProviderReason ?? 'No external provider is configured on the LORE backend.'}',
                  selected: appState.isAssistedMode,
                  enabled: appState.assistedAvailable,
                  onTap: () {
                    Navigator.of(sheetContext).pop();
                    _applyMode('assisted');
                  },
                ),
                const SizedBox(height: 14),
                Text(
                  'External answers are produced outside your backend. Private '
                  'Mode remains the default and is never changed automatically.',
                  style: LoreTypography.bodySm.copyWith(
                    color: LoreColors.secondary,
                    height: 1.5,
                  ),
                ),
              ],
            ),
          ),
        );
      },
    );
  }

  Future<void> _applyMode(String mode) async {
    final appState = context.read<AppState>();
    if (mode == appState.aiMode) return;

    if (mode == 'assisted') {
      final confirmed = await _confirm(
        title: 'Enable Assisted Mode?',
        message:
            'In Assisted Mode, LORE prepares document excerpts for a question '
            'and pauses. Nothing is sent until you approve that specific '
            'request. Approved excerpts leave the LORE backend and are '
            'processed by the configured external provider.',
        confirmLabel: 'Enable Assisted Mode',
      );
      if (!confirmed) return;
    }

    final success = await appState.setAiMode(mode);
    if (!mounted) return;
    if (!success) {
      _showSnack(appState.modeError ?? 'Could not change AI mode.');
      return;
    }

    if (mode == 'private') {
      final ask = context.read<AskController>();
      if (ask.isAwaitingApproval) {
        await ask.rejectAssisted();
      }
      _showSnack('Private Mode enabled.');
    } else {
      _showSnack(
        'Assisted Mode enabled. Every request will wait for your approval.',
      );
    }
  }

  Future<void> _runAction(String key, Future<String> Function() action) async {
    if (_runningAction != null) return;
    setState(() => _runningAction = key);
    try {
      final message = await action();
      if (!mounted) return;
      _showSnack(message);
    } catch (error) {
      if (!mounted) return;
      _showSnack(describeError(error));
    } finally {
      if (mounted) setState(() => _runningAction = null);
    }
  }

  Future<void> _rebuildSearchIndex() {
    final controller = context.read<DocumentsController>();
    return _runAction('search', () async {
      final result = await controller.rebuildSearchIndex();
      return 'Search index rebuilt for ${result.indexedDocuments} document${result.indexedDocuments == 1 ? '' : 's'}.';
    });
  }

  Future<void> _rebuildRelationships() {
    final controller = context.read<DocumentsController>();
    return _runAction('relationships', () async {
      final result = await controller.rebuildRelationships();
      return 'Processed ${result.processedDocuments} document${result.processedDocuments == 1 ? '' : 's'} and created ${result.relationshipsCreated} connection${result.relationshipsCreated == 1 ? '' : 's'}.';
    });
  }

  Future<void> _revokeConsent() async {
    final confirmed = await _confirm(
      title: 'Revoke prepared requests?',
      message:
          'Any assisted request waiting for approval will be cancelled. '
          'Nothing will be sent to an external provider.',
      confirmLabel: 'Revoke',
    );
    if (!confirmed || !mounted) return;

    final appState = context.read<AppState>();
    final ask = context.read<AskController>();
    await _runAction('revoke', () async {
      final count = await appState.client.revokeAssistedConsent();
      ask.clearPendingAfterRevocation();
      return 'Revoked $count prepared request${count == 1 ? '' : 's'}.';
    });
  }

  Future<void> _clearConversations() async {
    final confirmed = await _confirm(
      title: 'Clear session conversations?',
      message:
          'Conversation text is held in memory only. Clearing removes it from '
          'this session; documents and the backend index are not affected.',
      confirmLabel: 'Clear',
    );
    if (!confirmed || !mounted) return;
    context.read<AskController>().clearAllConversations();
    _showSnack('Session conversations cleared.');
  }

  Future<void> _showUnavailable(String title, String message) async {
    await showDialog<void>(
      context: context,
      builder: (dialogContext) => AlertDialog(
        title: Text(title),
        content: Text(message),
        actions: [
          TextButton(
            onPressed: () => Navigator.of(dialogContext).pop(),
            child: const Text('Close'),
          ),
        ],
      ),
    );
  }

