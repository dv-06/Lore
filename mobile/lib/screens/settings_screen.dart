  }
}

class _InfoRow extends StatelessWidget {
  final String title;
  final String subtitle;
  final Widget? trailing;
  final VoidCallback? onTap;

  const _InfoRow({
    required this.title,
    required this.subtitle,
    this.trailing,
    this.onTap,
