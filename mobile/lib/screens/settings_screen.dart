                    color: LoreColors.secondary,
                    height: 1.5,
                  ),
                ),
                const SizedBox(height: 12),
                for (final seconds in AuthController.autoLockOptions)
                  ListTile(
                    contentPadding: EdgeInsets.zero,
                    title: Text(
                      AuthController.autoLockLabel(seconds),
                      style: LoreTypography.bodyMd.copyWith(
                        color: LoreColors.onSurface,
                      ),
                    ),
                    trailing: auth.autoLockSeconds == seconds
                        ? const Icon(
                            Icons.check_circle,
                            color: LoreColors.primary,
                            size: 20,
                          )
                        : null,
                    onTap: () async {
                      Navigator.of(sheetContext).pop();
                      await auth.setAutoLockSeconds(seconds);
                    },
                  ),
              ],
            ),
          ),
        );
      },
    );
  }

  Future<void> _signOut() async {
    final auth = context.read<AuthController>();
    final confirmed = await _confirm(
      title: 'Sign out and forget this device?',
      message:
          'The backend session will be revoked and the stored token removed. '
          'You will need a new pairing code from the LORE backend to reconnect.',
      confirmLabel: 'Sign out',
    );
    if (!confirmed) return;
    await auth.logout();
  }

  Future<void> _revokeAllSessions() async {
    final auth = context.read<AuthController>();
    final confirmed = await _confirm(
      title: 'Revoke every backend session?',
      message:
          'Every paired device, including this one, must pair again with a new '
          'code. No documents are deleted.',
      confirmLabel: 'Revoke all',
    );
    if (!confirmed) return;
    final ok = await auth.revokeAllSessions();
    if (!ok && mounted && auth.error != null) {
      _showSnack(auth.error!);
    }
  }

