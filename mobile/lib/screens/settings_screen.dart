class _ModeOption extends StatelessWidget {
  final String title;
  final String badge;
  final String description;
  final bool selected;
  final bool enabled;
  final VoidCallback onTap;

  const _ModeOption({
    required this.title,
    required this.badge,
    required this.description,
    required this.selected,
    required this.enabled,
    required this.onTap,
  });

  @override
  Widget build(BuildContext context) {
    return InkWell(
      onTap: enabled ? onTap : null,
      borderRadius: LoreRadius.borderLg,
      child: Container(
        padding: const EdgeInsets.all(14),
        decoration: BoxDecoration(
          color: selected
              ? LoreColors.primaryFixed.withValues(alpha: 0.35)
              : LoreColors.surfaceContainerLow,
          borderRadius: LoreRadius.borderLg,
          border: Border.all(
            color: selected
                ? LoreColors.primary.withValues(alpha: 0.4)
                : LoreColors.structuralLine,
          ),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Expanded(
                  child: Text(
                    title,
                    style: LoreTypography.bodyMd.copyWith(
                      fontWeight: FontWeight.w600,
                      color: enabled
                          ? LoreColors.onSurface
                          : LoreColors.secondary,
                    ),
                  ),
                ),
                _StatusPill(
                  label: selected
                      ? (enabled ? 'Active' : 'Unavailable')
                      : badge,
                  active: selected && enabled,
                ),
              ],
            ),
            const SizedBox(height: 6),
            Text(
              description,
              style: LoreTypography.bodySm.copyWith(
                color: LoreColors.secondary,
                height: 1.5,
              ),
            ),
